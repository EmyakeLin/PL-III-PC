class Context():
    def __init__(self, parent = None, game = None):
        self.parent = parent
        if self.parent:
            self.game = self.parent.game
        else:
            self.game = game

        self.stack = []
        self.entries = []

        self.register = {}
        self.interceptions = []
        self.meta = {}

        # ==============================================================================
        # >>> Generated by Gemini >>>
        # ==============================================================================
        # 动态指令流与操作码调用栈 (Code Stream & Op Stack)
        self.code_stream = None
        self.op_stack = []

    @property
    def current_op(self):
        """当前处于审查/执行状态的操作码"""
        return self.op_stack[-1] if self.op_stack else None

    @current_op.setter
    def current_op(self, value):
        if self.op_stack:
            self.op_stack[-1] = value

    def cancel_op(self):
        """直接抹杀当前待执行的操作码（等同于纯栈操作 Pop OpCode）"""
        if self.op_stack:
            self.op_stack[-1] = None
