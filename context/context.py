    # <<< Generated by Gemini <<<
    # ==============================================================================

    def push(self, value):
        self.stack.append(value)

    def pop(self):
        """返回栈顶元素"""
        if len(self.stack) == 0:
            raise StackUnderflowError("栈下溢")
        return self.stack.pop()

    def peek(self, offset):
        """查看栈元素而不出栈"""
        if len(self.stack) <= offset:
            raise StackUnderflowError("offset 过大")
        return self.stack[-1-offset]

    def dup(self):
        """复制栈顶元素"""
        self.push(self.peek(0))

    def swap(self):
        """交换栈顶两个元素"""
        b = self.pop()
        a = self.pop()
        self.push(b)
        self.push(a)

    def store(self, name):
        """将栈顶存入寄存器"""
        self.register[name] = self.pop()

    def load(self, name):
        """从寄存器取值并压入栈顶，不清空寄存器"""
        if name in self.register:
            self.push(self.register.get(name))
        else:
            raise ValueError(f"Register does not contain {name}!")

