class DuelSlot():
    def __init__(self, game = None):
        self.game = game
        self.content = {}
        self.settled = False
        self.current_card_index = {}

    def add_content(self, side, content):
        if not self.content.get(side):
            self.content[side] = [content]
        else:
            self.content[side].append(content)

    def get_content(self, side):
        return self.content[side]

    # ==============================================================================
    # >>> Generated by Gemini >>>
    # ==============================================================================
    def has_next_card(self, side):
        cards = self.content.get(side, [])
        idx = self.current_card_index.get(side, 0)
        return idx < len(cards) and cards[idx] != ""

    def get_current_card(self, side):
        cards = self.content.get(side, [])
        idx = self.current_card_index.get(side, 0)
        return cards[idx] if (idx < len(cards) and cards[idx] != "") else None

    def get_current_opposing_card(self, attacking_side):
        """获取当前正处于前线与我对决的敌方卡牌 (current_opposing_card)"""
        enemy_side = 2 if attacking_side == 1 else 1
        return self.get_current_card(enemy_side)

    def advance_card(self, side):
        self.current_card_index[side] = self.current_card_index.get(side, 0) + 1

    def resolve_target_character(self, attacking_side, clash_pair=None):
        """
        受击目标角色确定：
        1. 拼点对决时 -> 对立面骰子所属角色；
        2. 无拼点但前线有敌方卡牌 -> current_opposing_card 所属角色（随换卡动态转移）；
        3. 槽位完全无卡 -> 交互询问玩家，回车使用可随时修改的默认目标！
        """
        enemy_side = 2 if attacking_side == 1 else 1
        if not self.game:
            return None
        enemy_player = [p for p in self.game.players if p.side == enemy_side][0]
        attacking_player = [p for p in self.game.players if p.side == attacking_side][0]

        # 1. 处于 ClashPair 拼点中
        if clash_pair and len(clash_pair.dice_dict) == 2:
            other_die = clash_pair.dice_dict.get(enemy_side)
            if other_die and hasattr(other_die, "card") and other_die.card:
                return other_die.card.character

        # 2. 槽位前线有敌方卡牌 (current_opposing_card)
        opposing_card = self.get_current_opposing_card(attacking_side)
        if opposing_card:
            return opposing_card.character

        # 3. 槽位全空（单方面攻击未匹配目标） -> 玩家决策或默认目标
        return attacking_player.choose_one_sided_target(enemy_player)
