class SidePipeline:
    """
    阵营私有管线 (SidePipeline):
    属于特定 Player/Side，独立维护待办队列与当前 PackType 位阶，
    在撞上 wait_xxx_check 节点时自我阻塞，等待主管线发包与恢复。
    """
    def __init__(self, side: int, game = None):
        self.side = side
        self.game = game
        self.queue = deque()
        self.blocked_at: Optional[Union[DynamicWaitNode, PipelineNode]] = None
        self.current_node: Optional[PipelineNode] = None

    @property
    def current_pack_type(self) -> PackType:
        if self.blocked_at:
            return getattr(self.blocked_at, "pack_type", PackType.NONE)
        if self.queue:
            return getattr(self.queue[0], "pack_type", PackType.NONE)
        return PackType.NONE

    def push_pack(self, pack_nodes: List[PipelineNode]):
        """将打包好的新 Section 注入到待办队列的最前列（展开），并解除当前阻塞"""
        self.blocked_at = None
        for node in reversed(pack_nodes):
            node.game = self.game
            self.queue.appendleft(node)

    def unblock(self):
        """仅解除当前 wait 节点的阻塞，继续往下流经"""
        self.blocked_at = None

    def is_blocked_at(self, check_id: str) -> bool:
        """检查当前管线是否被指定的检查节点阻塞"""
        return self.blocked_at is not None and self.blocked_at.id == check_id

    def step(self):
        """执行单步：若遇到 wait 节点则自我阻塞并停住"""
        if self.blocked_at is not None:
            return f"BLOCKED({self.blocked_at.id})"

        if not self.queue:
            return "NONE"

        node = self.queue.popleft()
        node.game = self.game
        node.side = self.side
        node.execute()

        if getattr(node, "is_wait_check", False):
            self.blocked_at = node
            return f"BLOCKED({node.id})"

        self.current_node = node
        return node.id


class Pipeline():
    """
    主游戏中央管线 (Pipeline):
    负责驱动战局宏观大周期，并在交锋阶段统筹、巡视各阵营 SidePipeline 的动态发包与偏序调度。
    """
    def __init__(self, game = None, step_list = []):
        self.game = game
        self.step_list = step_list
        self.current_step_index = -1
        self.is_finished = False

        # 持有各参战阵营的 SidePipeline
        self.side_pipelines: Dict[int, SidePipeline] = {}
        self.in_duel_phase = False

        # 当前拼点裁判实体与判定结果
        self.current_clash_pair = None
        self.current_clash_results = {}

    def init_side_pipelines(self, sides: List[int]):
        """为参战阵营初始化各自独立的 SidePipeline"""
        self.side_pipelines = {s: SidePipeline(s, self.game) for s in sides}

    def _get_current_duel(self):
        """安全获取当前交锋槽位实体，做足空指针收窄"""
        if self.game is not None and hasattr(self.game, "duelspace"):
            ds = self.game.duelspace
            idx = getattr(ds, "current_duel_index", 0)
            if 0 <= idx < len(ds.space):
                return ds.space[idx]
        return None

    def start_duel_combat(self):
        """开启交锋对战阶段，初始化双方 SidePipeline 并启动第一个交锋"""
        self.in_duel_phase = True
        sides = [p.side for p in self.game.players] if (self.game and hasattr(self.game, "players")) else [1, 2]
        self.init_side_pipelines(sides)
        self.check_duel_start()

    def check_duel_start(self):
        """检查当前槽位参战情况，向满足条件的 SidePipeline 注入 DUEL SECTION"""
        current_duel = self._get_current_duel()
        for side, pipe in self.side_pipelines.items():
            has_cards = False
            if current_duel and hasattr(current_duel, "content"):
                cards = current_duel.content.get(side, [])
                has_cards = any(c != "" for c in cards)
            if has_cards:
                pipe.push_pack(create_duel_pack())

    def _eligible_sides(self) -> List[int]:
        """当前槽位中真正放了卡的有效参战阵营"""
        current_duel = self._get_current_duel()
        eligible = []
        for side in self.side_pipelines:
            if current_duel and hasattr(current_duel, "content"):
                cards = current_duel.content.get(side, [])
                if any(c != "" for c in cards):
                    eligible.append(side)
        return eligible

    def check_and_dispatch(self) -> Optional[str]:
        """
        主管线巡视并分发 Packs：
        根据各个 SidePipeline 的阻塞状态以及战局事实做判定与发包。
        """
        dispatched_events = []
        current_duel = self._get_current_duel()
        eligible = self._eligible_sides()

        # 1. 检查技能展开检查点 (wait_skill_section_expand_check)
        for side, pipe in self.side_pipelines.items():
            if pipe.is_blocked_at("wait_skill_section_expand_check"):
                has_next = current_duel.has_next_card(side) if (current_duel and hasattr(current_duel, "has_next_card")) else False
                if has_next:
                    pipe.push_pack(create_skill_pack())
                    dispatched_events.append(f"Push Packed SKILL to Side {side}")
                else:
                    pipe.unblock()

        # 2. 检查骰子展开检查点 (wait_dice_section_expand_check)
        for side, pipe in self.side_pipelines.items():
            if pipe.is_blocked_at("wait_dice_section_expand_check"):
                current_card = current_duel.get_current_card(side) if (current_duel and hasattr(current_duel, "get_current_card")) else None
                has_next = current_card.has_next_die() if (current_card and hasattr(current_card, "has_next_die")) else False
                if has_next:
                    pipe.push_pack(create_dice_pack())
                    dispatched_events.append(f"Push Packed DICE to Side {side}")
                else:
                    pipe.unblock()

        # 3. 检查拼点检查点 (wait_can_clash_check)
        blocked_can_clash = [
            s for s in self.side_pipelines
            if self.side_pipelines[s].is_blocked_at("wait_can_clash_check")
        ]

        if blocked_can_clash and set(blocked_can_clash) == set(eligible):
            if len(eligible) >= 2:
                from models.duel import ClashPair
                dice_dict = {}
                for s in eligible:
                    card = current_duel.get_current_card(s) if (current_duel and hasattr(current_duel, "get_current_card")) else None
                    if card:
                        d = card.get_current_die(self.game)
                        if d:
                            dice_dict[s] = d

                # 检查双被动跳过拼点
                all_passive = len(dice_dict) >= 2 and all(getattr(d, "is_passive", False) for d in dice_dict.values())
                if all_passive:
                    for s in eligible:
                        self.side_pipelines[s].unblock()
                    dispatched_events.append("All passive dice -> Skip clash")
                else:
                    self.current_clash_pair = ClashPair(dice_dict)
                    for s in eligible:
                        self.side_pipelines[s].push_pack(create_clash_pack())
                    dispatched_events.append(f"ClashPair assembled: {list(dice_dict.keys())} -> Push Packed CLASH")
            elif len(eligible) == 1:
                solo_side = eligible[0]
                card = current_duel.get_current_card(solo_side) if (current_duel and hasattr(current_duel, "get_current_card")) else None
                die = card.get_current_die(self.game) if card else None
                pipe = self.side_pipelines[solo_side]
                pipe.unblock()
                if die and not getattr(die, "is_passive", False):
                    pipe.push_pack(create_dice_hit_pack())
                    dispatched_events.append(f"One-sided hit -> Push Packed DICE HIT to Side {solo_side}")

        # 4. 检查拼点结果检查点 (wait_clash_result_check)
        blocked_clash_result = [
            s for s in self.side_pipelines
            if self.side_pipelines[s].is_blocked_at("wait_clash_result_check")
        ]
        if blocked_clash_result and set(blocked_clash_result) == set(eligible):
            results = getattr(self, "current_clash_results", {})
            for s in eligible:
                res = results.get(s, "draw")
                if res == "win":
                    self.side_pipelines[s].push_pack(create_clash_win_pack())
                elif res == "lose":
                    self.side_pipelines[s].push_pack(create_clash_lose_pack())
                else:
                    self.side_pipelines[s].push_pack(create_clash_draw_pack())
            dispatched_events.append(f"Clash results dispatched: {results}")

        # 5. 检查命中检查点 (wait_can_hit_check)
        for s in eligible:
            pipe = self.side_pipelines[s]
            if pipe.is_blocked_at("wait_can_hit_check"):
                card = current_duel.get_current_card(s) if (current_duel and hasattr(current_duel, "get_current_card")) else None
                die = card.get_current_die(self.game) if card else None
                if die and not getattr(die, "is_passive", False):
                    pipe.push_pack(create_dice_hit_pack())
                    dispatched_events.append(f"Can hit verified -> Push Packed DICE HIT to Side {s}")
                else:
                    pipe.unblock()

        # 6. 检查交锋结束检查点 (wait_duel_section_expand_check)
        blocked_duel_expand = [
            s for s in self.side_pipelines
            if self.side_pipelines[s].is_blocked_at("wait_duel_section_expand_check")
        ]
        if blocked_duel_expand and set(blocked_duel_expand) == set(eligible):
            self.in_duel_phase = False
            dispatched_events.append("Duel Section completed")

        return "; ".join(dispatched_events) if dispatched_events else None

    def step_duel_combat(self):
        """
        交锋对战单步步进：
        依照 PackType 阶梯调度各阵营 SidePipeline 推进。
        """
        event = self.check_and_dispatch()
        if event:
            return ("[PIPELINE]", event)

        types = {s: self.side_pipelines[s].current_pack_type for s in self.side_pipelines}
        active_sides = [s for s in self.side_pipelines if types[s] != PackType.NONE]

        if not active_sides:
            self.in_duel_phase = False
            return ("FINISHED", "FINISHED")

        runnable_sides = set()
        if any(types[s] == PackType.HIT for s in active_sides):
            runnable_sides = {s for s in active_sides if types[s] == PackType.HIT}
        elif any(types[s] == PackType.DUEL for s in active_sides) and any(types[s] in (PackType.SKILL, PackType.DICE) for s in active_sides):
            runnable_sides = {s for s in active_sides if types[s] == PackType.DUEL}
        elif any(types[s] == PackType.SKILL for s in active_sides) and any(types[s] == PackType.DICE for s in active_sides):
            runnable_sides = {s for s in active_sides if types[s] == PackType.SKILL}
        else:
            runnable_sides = set(active_sides)

        results = {}
        for s in self.side_pipelines:
            pipe = self.side_pipelines[s]
            if types[s] == PackType.NONE:
                results[s] = None
            elif s not in runnable_sides:
                results[s] = f"WAIT_{types[s].name}"
            else:
                results[s] = pipe.step()

        side_list = sorted(self.side_pipelines.keys())
        return (results[side_list[0]], results[side_list[1]])
