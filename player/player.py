    def set_default_target(self, target):
        """玩家随时修改自己的默认单方面攻击目标"""
        self.default_target_character = target
        print(f"[{self.name}] 已将默认集火目标更新为: {getattr(target, 'name', target)}")

    def get_default_target(self, enemy_player):
        """获取当前有效的默认目标，若无或已阵亡则平滑回退至生命值最高者"""
        alive_enemies = [c for c in enemy_player.characters if getattr(c, "is_alive", True)]
        if not alive_enemies:
            return None
        if self.default_target_character in alive_enemies:
            return self.default_target_character
        return max(alive_enemies, key=lambda c: c.hp)

    def choose_one_sided_target(self, enemy_player):
        """交互选择单方面攻击目标，直接回车使用默认目标，输入 'set X' 永久修改默认目标"""
        alive_enemies = [c for c in enemy_player.characters if getattr(c, "is_alive", True)]
        if not alive_enemies:
            return None

        default_target = self.get_default_target(enemy_player)
        print(f"\n--- [{self.name}] 单方面攻击未匹配目标，请选择受击角色 ---")
        for idx, c in enumerate(alive_enemies, 1):
            tag = " [当前默认目标]" if c is default_target else ""
            print(f"  [{idx}] {c.name} (HP: {c.hp}){tag}")

        val = input(f"请输入目标编号 (直接回车攻击默认目标: {default_target.name}；输入 'set X' 永久修改默认目标): \n > ").strip()
        if val.startswith("set "):
            sub = val[4:].strip()
            if sub.isdigit() and 1 <= int(sub) <= len(alive_enemies):
                chosen = alive_enemies[int(sub) - 1]
                self.set_default_target(chosen)
                return chosen
        elif val.isdigit() and 1 <= int(val) <= len(alive_enemies):
            return alive_enemies[int(val) - 1]

        return default_target
